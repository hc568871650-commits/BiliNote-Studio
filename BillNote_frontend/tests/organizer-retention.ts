import assert from 'node:assert/strict'
import { webcrypto } from 'node:crypto'

const storage = new Map<string, string>()
Object.defineProperty(globalThis, 'localStorage', { value: { getItem: (key: string) => storage.get(key) || null, setItem: (key: string, value: string) => storage.set(key, value), removeItem: (key: string) => storage.delete(key) }, configurable: true })
Object.defineProperty(globalThis, 'location', { value: { search: '', hash: '', reload: () => {} }, configurable: true })
if (!globalThis.crypto) Object.defineProperty(globalThis, 'crypto', { value: webcrypto })
const seed = Array.from({ length: 10 }, (_, index) => {
  const id = `old-${index + 1}`
  return [id, { snapshot: { session_id: id, revision: 0, status: index >= 8 ? 'interrupted' : 'idle', query_scope: { kind: 'all' }, scope: { kind: 'all', authorized: false, exclude_favorites: false, target_count: 0 }, history: [{ id: `message-${id}`, role: 'user', content: `旧对话 ${index + 1}`, created_at: index + 1 }], messages: [], plan: null, result: null, error: null, events: [], target_summary: { count: 0, note_ids: [], folder_name: null, exclude_favorites: false, authorized: false }, updated_at: index + 1, pending_plan_id: null }, action: '', receipts: {} }]
})
storage.set('bilinote-organizer-preview-sessions-v1', JSON.stringify(seed))
storage.set('bilinote-organizer-active-session-v1', 'old-5')

async function run() {
  const mock = await import('@/dev/previewMock')
  const { default: request } = await import('@/utils/request')
  const api = await import('@/services/organizer')
  const { useOrganizerStore: store } = await import('@/store/organizerStore')
  const calls: { path: string; body: Record<string, unknown> }[] = []
  request.defaults.adapter = async config => { calls.push({ path: config.url || '', body: typeof config.data === 'string' ? JSON.parse(config.data) : config.data || {} }); return mock.previewAdapter(config) }
  const notesBefore = await request.get('/notes')
  assert.equal((await api.getOrganizerRetention()).limit, 10, 'Mock and server default retain ten sessions')
  const first = await api.previewOrganizerRetention('create')
  assert.equal(first.evictions[0].session_id, 'old-1')
  assert.equal(first.evictions[0].message_count, 1)
  assert.equal(first.protected_count, 2)
  assert.equal(typeof first.evictions[0].updated_at, 'number')
  assert.equal((await api.listOrganizerSessions()).sessions.length, 10, 'Preflight never removes sessions')
  await store.getState().initialize()
  store.getState().setDraft('新建取消后保留草稿')
  await store.getState().clear()
  assert.equal(store.getState().retentionPreview?.evictions.length, 1)
  assert.equal(store.getState().session?.session_id, 'old-5', 'Opening warning preserves existing session')
  store.getState().cancelCreation()
  assert.equal(store.getState().draft, '新建取消后保留草稿')
  assert.equal((await api.listOrganizerSessions()).sessions.length, 10)
  const body = { instruction: '首次发送草稿', scope: { kind: 'all' as const }, ...mock.previewDefaultModels.organizer }
  store.setState({ session: null, messages: [], draft: body.instruction })
  const callsBeforeEmptyCreation = calls.length
  await store.getState().clear()
  assert.equal(calls.length, callsBeforeEmptyCreation, 'An empty chat never requests creation or retention eviction')
  assert.equal(store.getState().retentionPreview, null, 'An empty chat does not open a reminder')
  assert.equal(store.getState().draft, body.instruction, 'An unsent draft is preserved')
  await store.getState().send(body, '')
  assert.ok(store.getState().retentionPreview)
  store.getState().cancelCreation()
  assert.equal(store.getState().draft, body.instruction, 'Lazy creation uses the same warning without discarding draft')
  assert.equal(calls.filter(call => call.path.endsWith('/message')).length, 0)
  await store.getState().send(body, '')
  const oldToken = store.getState().retentionPreview?.confirmation_token
  await api.messageOrganizerSession('old-2', { ...body, expected_revision: 0, request_id: crypto.randomUUID() })
  await store.getState().confirmCreation()
  assert.ok(store.getState().retentionPreview, 'Stale consent returns new warning, never auto-confirms')
  assert.notEqual(store.getState().retentionPreview?.confirmation_token, oldToken)
  assert.equal((await api.listOrganizerSessions()).sessions.length, 10)
  await store.getState().confirmCreation()
  assert.equal(store.getState().retentionPreview, null)
  assert.ok(store.getState().session)
  assert.equal(store.getState().draft, '', 'Confirmed lazy creation sends the original draft')
  assert.equal(store.getState().session?.history[0]?.content, body.instruction)
  const resumed = calls.filter(call => call.path.endsWith('/message')).at(-1)!
  assert.equal(resumed.body.provider_id, body.provider_id, 'Consent never changes purpose model selection')
  assert.deepEqual(resumed.body.scope, body.scope, 'Consent never changes the captured query scope')
  assert.equal((await api.listOrganizerSessions()).sessions.some(session => session.session_id === 'old-1'), false)
  const createCall = calls.filter(call => call.path === '/organizer/sessions' && call.body.confirmation_token).at(-1)!
  const duplicate = await request.post('/organizer/sessions', createCall.body) as unknown as { session_id: string }
  assert.equal(duplicate.session_id, store.getState().session?.session_id, 'Request receipt prevents duplicate creations')
  assert.equal((await api.listOrganizerSessions()).sessions.length, 10)
  const lower = await api.previewOrganizerRetention('set_limit', 3)
  assert.equal(lower.evictions.length, 7)
  await assert.rejects(api.setOrganizerRetention(3), (error: unknown) => api.retentionFailure(error)?.operation === 'set_limit')
  assert.equal((await api.getOrganizerRetention()).limit, 10, 'Unconfirmed setting leaves persisted limit unchanged')
  await api.setOrganizerRetention(3, lower.confirmation_token!)
  assert.equal((await api.getOrganizerRetention()).limit, 3)
  assert.equal(JSON.parse(storage.get(mock.PREVIEW_RETENTION_KEY)!).limit, 3)
  const blocked = await api.previewOrganizerRetention('set_limit', 1)
  assert.equal(blocked.blocked, true)
  assert.equal(blocked.confirmation_token, null)
  await assert.rejects(api.setOrganizerRetention(1), (error: unknown) => api.retentionFailure(error)?.blocked === true)
  assert.equal((await api.getOrganizerRetention()).limit, 3, 'Protected sessions prevent partial eviction or config change')
  assert.deepEqual(await request.get('/notes'), notesBefore, 'Session retention never changes note data')
  const removeActive = await api.previewOrganizerRetention('set_limit', 2)
  await api.setOrganizerRetention(2, removeActive.confirmation_token!)
  store.getState().setDraft('清理后仍保留输入')
  await store.getState().refresh()
  assert.equal(store.getState().session, null, 'Missing active session is released instead of trapping the page')
  assert.match(store.getState().error || '', /已被清理/)
  assert.equal(store.getState().draft, '清理后仍保留输入')
  await store.getState().send({ ...body, instruction: '受保护时不能创建' }, '')
  assert.equal(store.getState().retentionPreview, null)
  assert.match(store.getState().error || '', /受到保护/)
  assert.equal((await api.listOrganizerSessions()).sessions.length, 2)
  await assert.rejects(api.setOrganizerRetention(0))
  await assert.rejects(api.setOrganizerRetention(101))
  await assert.rejects(request.get('/unhandled-fixture-path'), 'Unimplemented preview URLs fail locally without network fallback')
  console.log('Organizer retention: pure preview, draft cancellation, stale consent, idempotency, protected sessions, persisted limits, missing active session and note isolation passed')
}
void run().catch(error => { console.error(error); process.exitCode = 1 })
