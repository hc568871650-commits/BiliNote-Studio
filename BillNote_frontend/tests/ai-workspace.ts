import assert from 'node:assert/strict'
import './send-shortcut'
import { webcrypto } from 'node:crypto'
import { readPersisted } from './shims/idb-keyval'
import type { ReadingAttachment } from '@/store/readingAssistantStore'
import type { Task } from '@/store/taskStore'
import { resolveReadableNote } from '@/utils/recentNote'

const browserStorage = new Map<string, string>()
Object.defineProperty(globalThis, 'localStorage', { value: {
  getItem: (key: string) => browserStorage.get(key) ?? null,
  setItem: (key: string, value: string) => browserStorage.set(key, String(value)),
  removeItem: (key: string) => browserStorage.delete(key),
}, configurable: true })
Object.defineProperty(globalThis, 'window', { value: { localStorage: globalThis.localStorage }, configurable: true })
if (!globalThis.crypto) Object.defineProperty(globalThis, 'crypto', { value: webcrypto })
const settle = async () => { for (let count = 0; count < 8; count++) await Promise.resolve() }
const attachment = (id: string): ReadingAttachment => ({ id, type: 'quote', name: '教程片段', text: `引用 ${id}`, taskId: 'note-a', versionId: 'v1', blockId: 'p1' })

async function run() {
  const note = (id: string, markdown: Task['markdown'], createdAt: string, extra: Partial<Task> = {}) => ({ id, markdown, createdAt, status: 'SUCCESS', ...extra }) as Task
  const older = note('older', '# 旧笔记', '2026-09-28T10:00:00+08:00')
  const recent = note('recent', '# 最近阅读', '2026-09-29T10:00:00+08:00')
  const newest = note('newest', '# 新笔记', '2026-10-01T10:00:00+08:00')
  const failedEmpty = note('failed-empty', '', '2026-10-01T11:00:00+08:00', { status: 'FAILED' })
  const archived = note('archived', '# 归档笔记', '2026-10-01T12:00:00+08:00', { archived_at: '2026-10-01' })
  const loading = note('loading', 'loading', '2026-10-01T13:00:00+08:00', { status: 'RUNNING' })
  const notes = [older, recent, newest, failedEmpty, archived, loading]
  const originalOrder = notes.map(item => item.id)
  assert.equal(resolveReadableNote(notes, older.id, recent.id)?.id, older.id, 'Current readable note takes precedence over recent and newest notes')
  assert.equal(resolveReadableNote(notes, failedEmpty.id, recent.id)?.id, recent.id, 'Failed empty current task restores recent readable note')
  assert.equal(resolveReadableNote(notes, loading.id, recent.id)?.id, recent.id, 'Loading placeholder is not a readable note')
  assert.equal(resolveReadableNote(notes, 'deleted-current', recent.id)?.id, recent.id, 'Deleted current note restores recent readable note')
  assert.equal(resolveReadableNote(notes, failedEmpty.id, 'deleted-recent')?.id, newest.id, 'Missing recent note falls back to latest non-archived readable note')
  assert.equal(resolveReadableNote(notes, null, failedEmpty.id)?.id, newest.id, 'Unreadable recent note cannot block readable fallback')
  assert.equal(resolveReadableNote([failedEmpty, loading], null, null), undefined, 'All unreadable notes produce an empty result')
  assert.equal(resolveReadableNote([], null, null), undefined, 'Empty library produces an empty result')
  assert.deepEqual(notes.map(item => item.id), originalOrder, 'Fallback sorting must not reorder the task store')
  const failedReadable = note('failed-readable', '# 上个版本仍可阅读', '2026-09-27T10:00:00+08:00', { status: 'FAILED' })
  assert.equal(resolveReadableNote([failedReadable, newest], failedReadable.id, null)?.id, failedReadable.id, 'Failed task with a readable existing version remains readable')
  const versioned = note('versioned', [{ ver_id: 'v1', content: '', style: 'default', model_name: 'same-model', created_at: '' }, { ver_id: 'v2', content: '# 可读版本', style: 'default', model_name: 'same-model', created_at: '' }], '2026-09-27T11:00:00+08:00', { status: 'FAILED' })
  assert.equal(resolveReadableNote([versioned, newest], null, versioned.id)?.id, versioned.id, 'Version arrays with readable content restore correctly')
  const { useReadingAssistantStore: reading, permanentSessionKey, temporarySessionKey } = await import('@/store/readingAssistantStore')
  const { usePurposeModelStore: purposes } = await import('@/store/purposeModelStore')
  const { readAttachment, wireAttachment } = await import('@/utils/readingAttachments')
  await reading.persist.rehydrate()
  reading.setState({ sessions: {} })
  const permanent = permanentSessionKey('a')
  const temporary = temporarySessionKey('a')
  reading.getState().patch(permanent, { input: '常驻草稿', model: { provider_id: 'provider-a', model_name: 'same-model' } })
  reading.getState().append(permanent, { id: 'p-message', role: 'assistant', content: '常驻答案' })
  reading.getState().attach(permanent, [attachment('p-attachment')])
  reading.getState().patch(temporary, { input: '临时草稿', model: { provider_id: 'provider-b', model_name: 'same-model' } })
  reading.getState().append(temporary, { id: 't-message', role: 'user', content: '临时问题' })
  reading.getState().attach(temporary, [attachment('t-attachment')])
  assert.equal(reading.getState().sessions[permanent].messages.length, 1, 'Temporary messages cannot leak into permanent chat')
  assert.equal(reading.getState().sessions[permanent].input, '常驻草稿')
  assert.equal(reading.getState().sessions[permanent].model?.provider_id, 'provider-a')
  await settle()
  const persisted = JSON.parse(String(readPersisted('bilinote-reading-assistant-v1')))
  assert.deepEqual(Object.keys(persisted.state.sessions), [permanent], 'Only permanent sessions are persisted')
  assert.equal(persisted.state.sessions[permanent].messages[0].content, '常驻答案')
  const transferSnapshots: boolean[] = []
  const unsubscribeTransfer = reading.subscribe(state => transferSnapshots.push(Boolean(state.sessions[temporary])))
  reading.getState().transfer(temporary, permanent)
  unsubscribeTransfer()
  assert.deepEqual(transferSnapshots, [false], 'Transfer publishes one atomic update with the temporary source already removed')
  assert.equal(reading.getState().sessions[temporary], undefined, 'Explicit transfer removes source session')
  assert.deepEqual(reading.getState().sessions[permanent].messages.map(message => message.id), ['p-message', 't-message'])
  assert.deepEqual(reading.getState().sessions[permanent].attachments.map(item => item.id), ['p-attachment', 't-attachment'])
  assert.equal(reading.getState().sessions[permanent].input, '常驻草稿\n临时草稿')
  assert.equal(reading.getState().sessions[permanent].model?.provider_id, 'provider-a', 'Transfer preserves target model')
  await settle()
  const transferred = JSON.parse(String(readPersisted('bilinote-reading-assistant-v1')))
  assert.equal(transferred.state.sessions[permanent].messages.length, 2, 'Transferred messages are retained in persisted permanent chat')
  reading.getState().patch(permanent, { attachments: Array.from({ length: 8 }, (_, index) => attachment(`full-${index}`)) })
  const beforeFull = structuredClone(reading.getState().sessions[permanent])
  assert.throws(() => reading.getState().attach(permanent, [attachment('overflow')]), /最多 8/)
  assert.deepEqual(reading.getState().sessions[permanent], beforeFull, 'Full attachment set is not silently truncated or mutated')
  reading.getState().patch(temporary, { input: '待转入', attachments: [attachment('still-temporary')] })
  assert.throws(() => reading.getState().transfer(temporary, permanent), /附件已满/)
  assert.equal(reading.getState().sessions[temporary].input, '待转入', 'Failed transfer keeps source intact')
  assert.deepEqual(reading.getState().sessions[permanent], beforeFull, 'Failed transfer keeps target intact')
  reading.getState().remove(temporary)
  assert.equal(reading.getState().sessions[permanent].messages.length, 2, 'Closing temporary chat cannot clear permanent chat')

  purposes.setState({ defaults: { generation: null, reading: null, organizer: null } })
  purposes.getState().setDefault('generation', { provider_id: 'provider-a', model_name: 'same-model' })
  purposes.getState().setDefault('reading', { provider_id: 'provider-b', model_name: 'same-model' })
  purposes.getState().setDefault('organizer', { provider_id: 'provider-c', model_name: 'same-model' })
  assert.deepEqual(Object.values(purposes.getState().defaults).map(model => model?.provider_id), ['provider-a', 'provider-b', 'provider-c'], 'Equal model names retain independent provider identity')
  purposes.getState().setDefault('reading', { provider_id: 'provider-d', model_name: 'another-model' })
  assert.equal(purposes.getState().defaults.generation?.provider_id, 'provider-a')
  assert.equal(purposes.getState().defaults.organizer?.provider_id, 'provider-c')
  const modelPersistence = JSON.parse(browserStorage.get('bilinote-purpose-models-v1')!)
  assert.deepEqual(Object.keys(modelPersistence.state.defaults.reading).sort(), ['model_name', 'provider_id'], 'Persist identities only, never keys or connection credentials')
  await purposes.persist.rehydrate()
  assert.equal(purposes.getState().getDefault('reading')?.provider_id, 'provider-d')
  purposes.getState().setDefault('reading', null)
  assert.equal(purposes.getState().defaults.reading, null)
  assert.equal(purposes.getState().defaults.generation?.provider_id, 'provider-a', 'Clearing one purpose cannot affect another')

  const text = await readAttachment(new File(['文本补充'], 'supplement.txt', { type: 'text/plain' }))
  const markdown = await readAttachment(new File(['# 标题\n内容'], 'lesson.MD', { type: 'text/markdown' }))
  assert.equal(text.type, 'text'); assert.equal(markdown.text, '# 标题\n内容')
  await assert.rejects(readAttachment(new File(['%PDF'], 'lesson.pdf', { type: 'application/pdf' })), /暂不支持 PDF/)
  await assert.rejects(readAttachment(new File(['x'.repeat(201 * 1024)], 'too-big.txt')), /200 KB/)
  await assert.rejects(readAttachment(new File(['x'.repeat(50001)], 'too-long.md')), /5 万字/)
  await assert.rejects(readAttachment(new File([' '], 'empty.txt')), /内容为空/)
  await assert.rejects(readAttachment(new File(['binary\u0000data'], 'bad.txt')), /UTF-8/)
  await assert.rejects(readAttachment(new File([new Uint8Array(2 * 1024 * 1024 + 1)], 'too-big.png', { type: 'image/png' })), /2 MB/)
  const local = Object.assign(attachment('local'), { path: 'C:\\private\\lesson.md', absolutePath: 'E:\\private\\lesson.md' })
  assert.deepEqual(wireAttachment(local), { type: 'quote', name: '教程片段', text: '引用 local' }, 'Wire payload excludes source metadata and local paths')
  assert.deepEqual(wireAttachment({ id: 'image', type: 'image', name: 'screenshot.png', data_url: 'data:image/png;base64,AA==', taskId: 'secret' }), { type: 'image', name: 'screenshot.png', data_url: 'data:image/png;base64,AA==' })

  const { settingsForModel, defaultAISettings, reasoningChoices, estimateLocalContext } = await import('@/utils/aiSettings')
  assert.equal(defaultAISettings.context_limit, 272000)
  assert.deepEqual(settingsForModel({ reasoning_effort: 'xhigh', context_limit: 64000 } as never, 'gemini-3.8-flash'), { reasoning_effort: 'auto', context_limit: 272000 })
  assert.ok(reasoningChoices('gpt-5.4').includes('xhigh'))
  assert.ok(!reasoningChoices('gpt-6-astra').includes('none'))
  assert.equal(settingsForModel({ reasoning_effort: 'high', context_limit: 272000 }, 'unknown-model').reasoning_effort, 'auto')
  assert.ok(estimateLocalContext([{ data_url: 'data:image/png;base64,' + 'x'.repeat(100000) }]) < 20000, 'Image estimates do not count base64 as text tokens')

  const { activeReadingMessages, compactedMemory, compressionPrefix } = await import('@/utils/readingContext')
  const fullHistory = Array.from({ length: 10 }, (_, index) => ({ id: `history-${index}`, role: (index % 2 ? 'assistant' : 'user') as 'user' | 'assistant', content: `历史${index}` }))
  const chat = { messages: fullHistory, input: '最新问题', attachments: [] }
  const sent = compressionPrefix(fullHistory)
  assert.equal(sent.length, 6, 'Keep the latest four messages verbatim')
  const compacted = { summary: '目标和约束摘要', consumed_messages: 6, compacted: true, before_tokens: 9000, after_tokens: 1500, context: {input_tokens:1500,estimated:true,limit:272000} }
  const memory = compactedMemory(chat, sent, compacted)
  assert.deepEqual(activeReadingMessages({ ...chat, memory }).map(m => m.id), ['history-6', 'history-7', 'history-8', 'history-9'])
  assert.equal(chat.messages.length, 10, 'Compaction preserves the original visible history')
  assert.equal(chat.input, '最新问题')
  assert.throws(() => compactedMemory({ ...chat, memory }, sent, compacted), /过期/)
  reading.getState().patch(temporary, { ...chat, memory })
  reading.getState().patch(permanent, { attachments: [] })
  reading.getState().transfer(temporary, permanent)
  assert.equal(reading.getState().sessions[permanent].memory, undefined, 'Merging chats resets summary cursors to avoid skipping unrelated history')

  const { compactCommandQuery, compactMenuKey } = await import('@/utils/slashCommands')
  for (const text of ['/', '/c', '/comp', '/compact', ' /COMPACT']) assert.ok(compactCommandQuery(text))
  for (const text of ['', '普通问题 /', '/other', 'https://example.com/', '/\n']) assert.ok(!compactCommandQuery(text))
  assert.equal(compactMenuKey({ key: 'Enter' }), 'choose')
  assert.equal(compactMenuKey({ key: 'Escape' }), 'dismiss')
  assert.equal(compactMenuKey({ key: 'ArrowDown' }), 'navigate')
  assert.equal(compactMenuKey({ key: 'Enter', nativeEvent: { isComposing: true } }), null, 'IME confirmation cannot execute a command')
  assert.equal(compactMenuKey({ key: 'Enter', ctrlKey: true }), null, 'Regular configured send shortcut remains separate')
  assert.equal(compactMenuKey({ key: 'Enter', shiftKey: true }), null, 'Shift+Enter still inserts a newline')

  // Versioned organizer sessions are exercised by check-organizer-session.mjs.
  console.log('PASS: recent-note recovery, readable failed versions, independent chats, temporary exclusion, explicit transfer, attachment saturation, purpose/provider isolation, safe attachments')
}
run().catch(error => { console.error(error); process.exitCode = 1 })
